"""Deterministic, user-friendly human-check notices for Scout.

A retrieved source is a lead, not proof of the cause of a live incident.
These notices are generated by code from saved evidence, never approved by
the language model. Human review is recorded separately in SQLite.
"""

from __future__ import annotations


def initial_verification_notice(evidence: dict) -> dict[str, str]:
    """Explain why an investigation reply needs a check by a person."""
    playbooks = evidence.get("playbooks") or []
    incidents = evidence.get("incidents") or []
    supporting_ids = set(evidence.get("supporting_incident_ids") or [])
    guides = evidence.get("guides") or []

    if playbooks:
        title = str(playbooks[0].get("title", "the first investigation step"))
        return {
            "title": "Confirm the suggested step fits your system",
            "source_state": "Reviewed procedure; applicability unconfirmed",
            "reason": (
                f"'{title}' comes from a reviewed investigation guide, but "
                "Scout chose it from reported symptoms. Scout cannot inspect "
                "your live configuration or prove the cause."
            ),
            "human_check": (
                "Confirm the technology and access permissions, then compare "
                "the suggested check with your own logs, timestamps and "
                "observations before acting."
            ),
        }
    if incidents:
        match_count = sum(
            str(item.get("doc_id", "")) in supporting_ids for item in incidents
        )
        return {
            "title": "Check whether the published incidents really match",
            "source_state": (
                "Published incident leads; current cause unconfirmed"
                if match_count else
                "Search results only; no incident match established"
            ),
            "reason": (
                "Scout found published reports, but they describe other "
                "organisations' incidents. Similar wording does not show "
                "that the same component or cause is affecting your system."
            ),
            "human_check": (
                "Open the original report and compare its symptoms, timing "
                "and affected components with your own evidence. Treat "
                "missing technical details as unknown."
            ),
        }
    if guides:
        return {
            "title": "Check technical guidance before using it",
            "source_state": "Technical references available; applicability unconfirmed",
            "reason": (
                "Scout found technical documentation, but there was no "
                "checked investigation playbook selected for this case."
            ),
            "human_check": (
                "Confirm which technology and version you use, read the "
                "linked documentation and check it against your live logs."
            ),
        }
    return {
        "title": "More evidence is needed",
        "source_state": "No supporting incident or checked procedure selected",
        "reason": (
            "Scout could not establish a relevant published incident or "
            "select a checked investigation procedure from the information provided."
        ),
        "human_check": (
            "Confirm the affected service, error message, start time and "
            "recent changes. Add those observations to the case before "
            "drawing a conclusion."
        ),
    }


def ai_verification_notice(evidence: dict) -> dict[str, str]:
    """Even a well-cited model draft cannot approve its own interpretation."""
    cited = set(evidence.get("model_draft_cited_ids") or [])
    known = {
        str(item.get("doc_id"))
        for item in evidence.get("incidents", [])
        if item.get("doc_id")
    } | {
        str(item.get("kb_id"))
        for item in evidence.get("guides", [])
        if item.get("kb_id")
    }

    if not cited:
        reason = (
            "No usable source IDs were captured for this AI interpretation. "
            "A plausible explanation without a traceable source is not verified."
        )
    elif cited - known:
        reason = (
            "Some source IDs cited by the AI are not in this reply's saved "
            "evidence. Scout cannot check those references."
        )
    else:
        reason = (
            "The AI refers to saved sources, but source IDs alone do not "
            "prove that its explanations or proposed actions are correct."
        )
    return {
        "title": "Review the AI interpretation separately",
        "source_state": "AI-generated commentary; not independently verified",
        "reason": reason,
        "human_check": (
            "Check each material claim against the linked original source "
            "and your own system observations. Confirm commands and "
            "applicability before running anything."
        ),
    }
